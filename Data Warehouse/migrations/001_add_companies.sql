COMMENT ON INDEX uq_anomaly_open_expense_spike  IS 'At most one OPEN expense_spike alert per (workspace, category, month) -- the category/month key alone would collide across workspaces. detect_anomalies() targets this predicate in ON CONFLICT for idempotency.';

