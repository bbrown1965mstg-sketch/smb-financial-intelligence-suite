-- =============================================================================
--  SMB FINANCIAL & OPERATIONAL DATA WAREHOUSE
--  File   : migrations/001_add_companies.sql
--  Purpose: multi-client (Fractional CFO) migration -- introduces the
--           `companies` registry and scopes the 8 client-data tables by
--           company_id. Market/global data (market_benchmarks,
--           backtest_results, the SoCal tables, the SoCal Capital & Peer
--           modules) is deliberately NOT scoped.
--
--  IDEMPOTENT: safe to re-run on any warehouse state (fresh container boot,
--  persisted volume that predates this migration, or an already-migrated
--  database). docker/init_pipeline.py applies it on EVERY boot, after the
--  schema files.
--
--  WHAT IT DOES (per table, in order):
--    1. CREATE TABLE IF NOT EXISTS companies (identity PK, unique name,
--       industry_vertical, socal_region, created_at).
--    2. INSERT the demo company 'BrightPath Works (Demo)'
--       (industry_vertical 'home_services_remodeling', socal_region NULL)
--       ON CONFLICT (company_name) DO NOTHING.
--    3. For each of the 8 client tables (customers, job_types, employees,
--       jobs, financial_ledger, labor_logs, anomaly_alerts, forecasts):
--         a. ADD COLUMN IF NOT EXISTS company_id BIGINT (nullable first, so
--            legacy rows can be backfilled);
--         b. backfill every NULL company_id with the demo company's id
--            (all pre-existing rows become Company #1);
--         c. a DO block that verifies zero NULLs remain (fails LOUDLY inside
--            the transaction if any row cannot be backfilled) and then
--            ALTER COLUMN ... SET NOT NULL (a no-op when already set);
--            plus SET DEFAULT 1 so legacy/unscoped writers land in the
--            demo workspace instead of failing (production writers all
--            set company_id explicitly);
--         d. (re)create the named FK fk_<table>_company_id with an explicit
--            ON DELETE RESTRICT policy (the warehouse's convention: a
--            company with dependent history cannot be deleted). The drop
--            covers BOTH this migration's named constraint and the
--            auto-named NO ACTION constraint a legacy `ADD COLUMN ...
--            REFERENCES` run would have left behind, so re-runs normalize
--            the policy instead of duplicating constraints;
--         e. CREATE INDEX IF NOT EXISTS idx_<table>_company_id.
--    4. Re-key the uniqueness that must now be per company:
--         * forecasts.uq_forecasts_series_period_model  ->
--             UNIQUE (company_id, series, period_start, model)
--           (two clients' revenue forecasts for the same month must not
--           collide; the engine upserts per company);
--         * the anomaly_alerts OPEN-alert partial unique indexes gain
--           company_id, so two clients can each have an open alert for the
--           same (category, month) / job without suppressing each other.
--
--  APPLY:
--    psql "postgresql://postgres:postgres@localhost:5432/smb_warehouse" \
--         -v ON_ERROR_STOP=1 -f migrations/001_add_companies.sql
--  Everything runs in ONE transaction: any failure rolls the whole
--  migration back and the database is left untouched.
-- =============================================================================

