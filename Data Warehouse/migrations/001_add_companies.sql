-- 1) companies registry
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS companies (
    company_id        BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name      TEXT        NOT NULL UNIQUE,
    industry_vertical TEXT,
    socal_region      TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE  companies                IS 'Client registry for the Fractional CFO multi-tenant warehouse. Every client-data table (customers, job_types, employees, jobs, financial_ledger, labor_logs, anomaly_alerts, forecasts) carries company_id FK to this table; market/global data (market_benchmarks, backtest_results, the SoCal tables and modules) is shared across clients and carries none.';
COMMENT ON COLUMN companies.company_id        IS 'Surrogate identity key referenced by the 8 client-data tables.';
COMMENT ON COLUMN companies.company_name      IS 'Client workspace display name (unique).';
COMMENT ON COLUMN companies.industry_vertical IS 'Free-text vertical label (e.g. home_services_remodeling); informational.';
COMMENT ON COLUMN companies.socal_region      IS 'Optional fixed SoCal region_code from the 6-region vocabulary (la_msa, oxnard_ventura_msa, orange_county, san_diego_msa, inland_empire_msa, california_state); NULL when not applicable.';
COMMENT ON COLUMN companies.created_at        IS 'Row creation time (application-maintained; no triggers by design).';

-- The demo workspace. Every pre-existing row of the warehouse belongs to it
-- (backfill below), so all counts and analytics are unchanged by this
-- migration. Insert is guarded so re-runs never duplicate it.
INSERT INTO companies (company_name, industry_vertical, socal_region)
VALUES ('BrightPath Works (Demo)', 'home_services_remodeling', NULL)
ON CONFLICT (company_name) DO NOTHING;

-- -----------------------------------------------------------------------------
-- 2) company_id on the 8 client-data tables
--    Pattern per table (idempotent at every step):
--      a. ADD COLUMN IF NOT EXISTS (nullable first, so old rows can exist)
--      b. backfill NULLs -> demo company
--      c. DO block: verify no NULLs remain, then SET NOT NULL
--      d. FK index IF NOT EXISTS
-- -----------------------------------------------------------------------------

-- customers -------------------------------------------------------------------
ALTER TABLE customers
    ADD COLUMN IF NOT EXISTS company_id BIGINT;
UPDATE customers
   SET company_id = (SELECT company_id FROM companies
                      WHERE company_name = 'BrightPath Works (Demo)')
 WHERE company_id IS NULL;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM customers WHERE company_id IS NULL) THEN
        RAISE EXCEPTION 'customers: rows with NULL company_id remain; backfill failed';
    END IF;
END $$;
ALTER TABLE customers ALTER COLUMN company_id SET NOT NULL;
-- Scratch/legacy-writer safety net: unscoped INSERTs (pre-migration
-- ad-hoc SQL, QA fixture graphs) land in the demo workspace instead of
-- failing. Every production writer (seed_demo.py, ingest_csv.py,
-- forecast_engine.py, detect_anomalies()) sets company_id explicitly.
ALTER TABLE customers ALTER COLUMN company_id SET DEFAULT 1;
-- (Re)create the named company FK with an explicit ON DELETE RESTRICT
-- policy (the ADD COLUMN ... REFERENCES form of a legacy run leaves
-- an auto-named NO ACTION constraint; drop both candidate names and
-- re-add the canonical one -- idempotent on every re-run).
ALTER TABLE customers DROP CONSTRAINT IF EXISTS fk_customers_company_id;
ALTER TABLE customers DROP CONSTRAINT IF EXISTS customers_company_id_fkey;
ALTER TABLE customers
    ADD CONSTRAINT fk_customers_company_id
    FOREIGN KEY (company_id) REFERENCES companies (company_id)
    ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS idx_customers_company_id ON customers (company_id);
COMMENT ON COLUMN customers.company_id IS 'Client workspace this customer belongs to (Fractional CFO multi-tenancy).';

