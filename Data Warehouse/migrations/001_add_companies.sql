-- anomaly_alerts OPEN-alert dedup: the expense-spike key (category, period)
-- is NOT unique across workspaces (two clients can spike 'materials' in the
-- same month), so both partial unique indexes gain company_id. The detector's
-- ON CONFLICT clauses (analytics_views.sql) target the new column lists.
DROP INDEX IF EXISTS uq_anomaly_open_labor_overrun;
