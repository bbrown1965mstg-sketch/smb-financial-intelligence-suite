def test_cli_export_flags_cross_file_duplicate(tmp_path):
    """export_warehouse_csv.main() must categorize the FULL transaction set
    once, so duplicate detection sees across files (regression: it used to
    categorize per-PDF, which never detected the re-sent invoice)."""
    import csv

    export_mod = pytest.importorskip("export_warehouse_csv")
    pdfs_dir = os.path.join(PROJECT_DIR, "sample_pdfs")
    out_dir = str(tmp_path / "cli_out")
    rc = export_mod.main(["--pdfs", pdfs_dir, "--out", out_dir])
    assert rc == 0, "CLI main() must exit 0 on the sample corpus"
    ledger_path = os.path.join(out_dir, "financial_ledger.csv")
    assert os.path.isfile(ledger_path), "CLI must write financial_ledger.csv"
    with open(ledger_path, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    resend = [r for r in rows
              if r.get("source_file") == "invoice_abc_lumber_resend.pdf"]
    assert len(resend) == 1, "exactly one re-send invoice row expected"
    assert resend[0].get("is_duplicate") == "True", (
        "CLI export must flag the re-sent invoice as a cross-file duplicate "
        "(is_duplicate=True in financial_ledger.csv)")
    assert resend[0].get("duplicate_of", "").startswith("invoice_abc_lumber.pdf:"), (
        "duplicate_of must point at the original invoice's txn_id, got %r"
        % resend[0].get("duplicate_of"))
    originals = [r for r in rows
                 if r.get("source_file") == "invoice_abc_lumber.pdf"]
    assert originals and originals[0].get("is_duplicate") != "True", (
        "the ORIGINAL invoice must not itself be flagged as duplicate")
