def test_ground_truth_internal_consistency(ground_truth):
    """Re-assert (independently of the generator) that the ground truth
    itself adds up: invoice line items -> subtotal -> total, payroll rows
    -> TOTAL GROSS, bank running balance -> final balance."""
    from generate_sample_pdfs import BEGINNING_BALANCE

    total_txns = 0
    for doc in ground_truth["documents"]:
        total_txns += len(doc["transactions"])
        if doc["doc_type"] == "invoice":
            txn = doc["transactions"][0]
            totals = doc["expected_totals"]
            line_sum = sum((D(li["amount"]) for li in txn["line_items"]), ZERO)
            assert line_sum == D(totals["subtotal"]), (
                "%s: line items sum %s != subtotal %s"
                % (doc["file"], line_sum, totals["subtotal"]))
            assert line_sum + D(totals["tax"]) == D(totals["total"]), (
                "%s: subtotal+tax != total" % doc["file"])
            assert D(txn["amount"]) == D(totals["total"]), (
                "%s: transaction amount != total" % doc["file"])
        elif doc["doc_type"] == "payroll":
            txn = doc["transactions"][0]
            items = txn["line_items"]
            assert len(items) == 16, "payroll must define 16 rows, found %d" % len(items)
            gross = sum((D(li["amount"]) for li in items), ZERO)
            assert gross == D(doc["expected_totals"]["total_gross"]), (
                "payroll rows sum %s != TOTAL GROSS" % gross)
            for li in items:
                assert D(li["hours"]) * D(li["rate"]) == D(li["amount"]), (
                    "payroll row hours*rate != amount: %r" % li)
        else:
            totals = doc["expected_totals"]
            credits = sum((D(t["amount"]) for t in doc["transactions"]
                           if t["direction"] == "in"), ZERO)
            debits = sum((D(t["amount"]) for t in doc["transactions"]
                          if t["direction"] == "out"), ZERO)
            assert credits == D(totals["total_credits"]), "bank credits do not add up"
            assert debits == D(totals["total_debits"]), "bank debits do not add up"
            assert BEGINNING_BALANCE + credits - debits == D(totals["final_balance"]), (
                "bank running balance does not reconcile to final_balance")

    # 15 bank rows + 4 invoice transactions + 1 payroll transaction = 20.
    assert total_txns == 20, "expected 20 ground-truth transactions, found %d" % total_txns


