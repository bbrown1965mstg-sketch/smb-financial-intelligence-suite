def test_bank_transactions_extracted_exactly(ground_truth, categorized_transactions):
    doc = gt_doc(ground_truth, BANK_FILE)
    ext = txns_for(categorized_transactions, BANK_FILE)
    gt_txns = doc["transactions"]

    assert len(ext) == len(gt_txns) == 15, (
        "bank statement: expected %d transactions, extracted %d"
        % (len(gt_txns), len(ext)))

    extracted_keys = Counter((t.get("date"), amt(t.get("amount")), t.get("direction"))
                             for t in ext)
    for gt_txn in gt_txns:
        key = (gt_txn["date"], amt(gt_txn["amount"]), gt_txn["direction"])
        assert extracted_keys[key] == 1, (
            "bank row %r must match exactly one extracted row, found %d (all: %r)"
            % (key, extracted_keys[key], dict(extracted_keys)))
    # Bijection: every GT row matched once AND nothing extra was extracted.
    assert sum(extracted_keys.values()) == len(gt_txns), (
        "bank statement has unmatched extra rows: %r"
        % [t for t in ext
           if (t.get("date"), amt(t.get("amount")), t.get("direction"))
           not in {(g["date"], amt(g["amount"]), g["direction"]) for g in gt_txns}])

    credits = sum((D(t["amount"]) for t in ext if t["direction"] == "in"), ZERO)
    debits = sum((D(t["amount"]) for t in ext if t["direction"] == "out"), ZERO)
    assert credits == D(doc["expected_totals"]["total_credits"]), (
        "bank credits %s != expected %s" % (credits, doc["expected_totals"]["total_credits"]))
    assert debits == D(doc["expected_totals"]["total_debits"]), (
        "bank debits %s != expected %s" % (debits, doc["expected_totals"]["total_debits"]))


def test_aggregate_totals_match_ground_truth_to_the_penny(ground_truth,
                                                          categorized_transactions):
    gt_in = sum((D(t["amount"]) for doc in ground_truth["documents"]
                 for t in doc["transactions"] if t["direction"] == "in"), ZERO)
    gt_out = sum((D(t["amount"]) for doc in ground_truth["documents"]
                  for t in doc["transactions"] if t["direction"] == "out"), ZERO)
    ext_in = sum((D(t["amount"]) for t in categorized_transactions
                  if t.get("direction") == "in"), ZERO)
    ext_out = sum((D(t["amount"]) for t in categorized_transactions
                   if t.get("direction") == "out"), ZERO)
    assert ext_in == gt_in, "aggregate inflow %s != ground truth %s" % (ext_in, gt_in)
    assert ext_out == gt_out, "aggregate outflow %s != ground truth %s" % (ext_out, gt_out)


