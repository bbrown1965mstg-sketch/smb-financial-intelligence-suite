@pytest.mark.parametrize("file_name", INVOICE_FILES)
def test_invoice_extracted_completely(ground_truth, categorized_transactions, file_name):
    doc = gt_doc(ground_truth, file_name)
    gt_txn = doc["transactions"][0]
    ext = txns_for(categorized_transactions, file_name)

    assert len(ext) == 1, (
        "%s: expected 1 invoice transaction, extracted %d" % (file_name, len(ext)))
    txn = ext[0]

    assert txn.get("invoice_number") == gt_txn["invoice_number"], (
        "%s: invoice_number %r != %r"
        % (file_name, txn.get("invoice_number"), gt_txn["invoice_number"]))
    assert txn.get("date") == gt_txn["date"], (
        "%s: date %r != %r" % (file_name, txn.get("date"), gt_txn["date"]))
    assert amt(txn.get("amount")) == amt(gt_txn["amount"]), (
        "%s: amount %r != %r" % (file_name, txn.get("amount"), gt_txn["amount"]))
    assert amt(txn["amount"]) == amt(doc["expected_totals"]["total"]), (
        "%s: amount != expected_totals.total to the penny" % file_name)
    assert txn.get("direction") == "out"

    items = txn.get("line_items") or []
    assert len(items) == len(gt_txn["line_items"]), (
        "%s: extracted %d line items, ground truth defines %d"
        % (file_name, len(items), len(gt_txn["line_items"])))

    for gt_li in gt_txn["line_items"]:
        candidates = [li for li in items if amt(li.get("amount")) == amt(gt_li["amount"])]
        assert len(candidates) == 1, (
            "%s: line item amount %s must appear exactly once, found %d"
            % (file_name, amt(gt_li["amount"]), len(candidates)))
        li = candidates[0]
        assert amt(li.get("unit_price")) == amt(gt_li["unit_price"]), (
            "%s: unit_price %r != %r for amount %s"
            % (file_name, li.get("unit_price"), gt_li["unit_price"], amt(gt_li["amount"])))
        assert D(li.get("qty")) == D(gt_li["qty"]), (
            "%s: qty %r != %r for amount %s"
            % (file_name, li.get("qty"), gt_li["qty"], amt(gt_li["amount"])))
        assert norm(li.get("description")) == norm(gt_li["description"]), (
            "%s: line item description %r != %r"
            % (file_name, li.get("description"), gt_li["description"]))


