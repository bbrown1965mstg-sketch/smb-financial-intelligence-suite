"""Acceptance tests for the Doc-to-Warehouse extraction pipeline (Agent 2).

Locks in the CONTRACT.md section 7 acceptance criteria against the sample
corpus generated by ``generate_sample_pdfs.py``. All tests:

  * run WITHOUT any GLM API key (pure rule-based extraction);
  * are independent of execution order (all state comes from session
    fixtures defined in conftest.py);
  * compare money via ``Decimal(str(x))`` on BOTH sides, so penny equality
    is exact (never raw float equality).

Test-side matching rules (deliberate, documented):
  * bank rows are matched 1:1 on (date, amount, direction) -- every bank
    amount in the corpus is unique, so this is a bijection;
  * invoice transactions are matched by source_file + invoice_number;
  * payroll is one transaction per document; its line items are matched on
    (employee, work_date);
  * line-item descriptions are compared after whitespace collapse/casefold
    (the parser may join wrapped lines with any whitespace).

Interpretation notes (reported, not silently assumed):
  * CONTRACT.md 7.1 asks for date/vendor/description/amount matches. For
    bank rows this suite matches on (date, amount, direction) per the
    agreed test plan; vendor correctness for bank rows is exercised
    indirectly by the categorization test (category signals are
    vendor/description driven). Invoice/payroll dates, amounts, quantities
    and line-item descriptions are asserted directly.
  * The financial ledger is expected to contain one row per extracted
    transaction (20 rows): bank rows, the four invoices and the payroll
    summary each map 1:1. The re-send duplicate STAYS in the ledger,
    flagged via its is_duplicate/duplicate_of columns -- those columns
    exist precisely to carry duplicates forward, and CONTRACT.md section 6
    defines no exclusion rule.
"""

