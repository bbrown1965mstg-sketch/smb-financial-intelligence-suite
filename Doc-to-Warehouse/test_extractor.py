def test_csv_amounts_positive_and_entry_types(exported):
    labor = 0
    for i, row in enumerate(exported["financial_rows"]):
        try:
            value = Decimal(row["amount"])
        except (InvalidOperation, TypeError, KeyError) as exc:
            raise AssertionError(
                "financial_ledger.csv row %d: amount %r does not parse as Decimal (%s)"
                % (i, row.get("amount"), exc))
        assert value > ZERO, "financial_ledger.csv row %d: amount %s must be > 0" % (i, value)

        entry_type = (row.get("entry_type") or "").strip().casefold()
        category = (row.get("extracted_category") or "").strip()
        combined = "%s/%s" % (entry_type, (row.get("category") or "").strip().casefold())
        if category == "Revenue":
            assert entry_type == "revenue", (
                "financial_ledger.csv row %d: revenue row must carry "
                "entry_type=revenue, got %r" % (i, row.get("entry_type")))
        else:
            assert entry_type.startswith("expense"), (
                "financial_ledger.csv row %d: non-revenue row must carry an "
                "expense entry_type, got %r" % (i, row.get("entry_type")))
            if category in ("Direct_Materials", "Subcontractor", "Marketing", "Payroll"):
                token = {"Direct_Materials": "materials", "Subcontractor": "subcontractor",
                         "Marketing": "marketing", "Payroll": "payroll"}[category]
                assert token in combined, (
                    "financial_ledger.csv row %d: warehouse mapping for %r must "
                    "reference %r, got entry_type=%r category=%r"
                    % (i, category, token, row.get("entry_type"), row.get("category")))
        if category == "Payroll":
            labor += 1
    assert labor == 1, "expected exactly one expense/payroll ledger row, found %d" % labor


