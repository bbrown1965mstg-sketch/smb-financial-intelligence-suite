def test_csv_labor_rows_within_warehouse_ranges(exported):
    iso_date = re.compile(r"^\d{4}-\d{2}-\d{2}$")
    for i, row in enumerate(exported["labor_rows"]):
        try:
            hours = Decimal(row["hours"])
            rate = Decimal(row["hourly_rate"])
        except (InvalidOperation, TypeError, KeyError) as exc:
            raise AssertionError(
                "labor_logs.csv row %d: hours=%r rate=%r must parse as Decimal (%s)"
                % (i, row.get("hours"), row.get("hourly_rate"), exc))
        assert ZERO < hours <= Decimal("24"), (
            "labor_logs.csv row %d: hours %s outside warehouse CHECK range (0 < h <= 24)"
            % (i, hours))
        assert rate >= ZERO, (
            "labor_logs.csv row %d: hourly_rate %s must be >= 0" % (i, rate))
        assert iso_date.match(row.get("work_date") or ""), (
            "labor_logs.csv row %d: work_date %r is not ISO YYYY-MM-DD"
            % (i, row.get("work_date")))
        assert (row.get("employee_name") or "").strip(), (
            "labor_logs.csv row %d: employee_name must be non-empty" % i)


