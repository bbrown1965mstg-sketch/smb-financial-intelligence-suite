def test_payroll_rows_extracted(ground_truth, categorized_transactions):
    doc = gt_doc(ground_truth, PAYROLL_FILE)
    gt_txn = doc["transactions"][0]
    ext = txns_for(categorized_transactions, PAYROLL_FILE)

    assert len(ext) == 1, "payroll must yield exactly one aggregate transaction"
    txn = ext[0]

    items = txn.get("line_items") or []
    assert len(items) == len(gt_txn["line_items"]) == 16, (
        "payroll: extracted %d line items, expected 16" % len(items))

    for gt_li in gt_txn["line_items"]:
        candidates = [li for li in items
                      if norm(li.get("employee")) == norm(gt_li["employee"])
                      and li.get("work_date") == gt_li["work_date"]]
        assert len(candidates) == 1, (
            "payroll row (%s, %s) must appear exactly once, found %d"
            % (gt_li["employee"], gt_li["work_date"], len(candidates)))
        li = candidates[0]
        assert amt(li.get("hours")) == amt(gt_li["hours"]), (
            "payroll (%s, %s): hours %r != %r"
            % (gt_li["employee"], gt_li["work_date"], li.get("hours"), gt_li["hours"]))
        assert amt(li.get("rate")) == amt(gt_li["rate"]), (
            "payroll (%s, %s): rate %r != %r"
            % (gt_li["employee"], gt_li["work_date"], li.get("rate"), gt_li["rate"]))
        assert amt(li.get("amount")) == amt(gt_li["amount"]), (
            "payroll (%s, %s): amount %r != %r"
            % (gt_li["employee"], gt_li["work_date"], li.get("amount"), gt_li["amount"]))

    assert txn.get("date") == gt_txn["date"], (
        "payroll transaction date %r != %r" % (txn.get("date"), gt_txn["date"]))
    assert amt(txn.get("amount")) == amt(gt_txn["amount"]), (
        "payroll aggregate amount %r != TOTAL GROSS %s"
        % (txn.get("amount"), amt(gt_txn["amount"])))
    assert amt(txn["amount"]) == amt(doc["expected_totals"]["total_gross"]), (
        "payroll aggregate amount != expected_totals.total_gross to the penny")


