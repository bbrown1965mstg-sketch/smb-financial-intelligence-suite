# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def D(value) -> Decimal:
    """Decimal(str(x)) -- the penny-exact comparison both sides use."""
    return Decimal(str(value))


def amt(value) -> str:
    """Normalize any amount (float/str/Decimal) to a 2dp decimal string."""
    return "{:.2f}".format(D(value))


def norm(text) -> str:
    """Whitespace-collapsed, casefolded text for description comparisons."""
    return " ".join(str(text if text is not None else "").split()).casefold()


def gt_doc(ground_truth: dict, file_name: str) -> dict:
    for doc in ground_truth["documents"]:
        if doc["file"] == file_name:
            return doc
    raise AssertionError("ground truth has no document %r" % file_name)


def txns_for(transactions: list, file_name: str) -> list:
    return [t for t in transactions if t.get("source_file") == file_name]


def find_gt_match(transactions: list, doc: dict, gt_txn: dict) -> dict:
    """Find the ONE extracted transaction corresponding to a GT transaction."""
    candidates = txns_for(transactions, doc["file"])
    if doc["doc_type"] == "bank_statement":
        key = (gt_txn["date"], amt(gt_txn["amount"]), gt_txn["direction"])
        candidates = [t for t in candidates
                      if (t.get("date"), amt(t.get("amount")), t.get("direction")) == key]
    elif doc["doc_type"] == "invoice":
        candidates = [t for t in candidates
                      if t.get("invoice_number") == gt_txn["invoice_number"]]
    # payroll: exactly one transaction per document, no extra filter
    assert len(candidates) == 1, (
        "expected exactly 1 extracted transaction for %s (key %r), found %d: %r"
        % (doc["file"],
           key if doc["doc_type"] == "bank_statement" else gt_txn.get("invoice_number", "payroll"),
           len(candidates), candidates))
    return candidates[0]


def _gt_txn_params():
    """Static (file, index) list for the categorization parametrization.

    Built from generate_sample_pdfs.GROUND_TRUTH (import-time data only, no
    files needed) so test IDs are stable before any fixture runs.
    """
    from generate_sample_pdfs import GROUND_TRUTH
    params = []
    for doc in GROUND_TRUTH["documents"]:
        for idx in range(len(doc["transactions"])):
            params.append((doc["file"], idx))
    return params


