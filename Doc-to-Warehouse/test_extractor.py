def test_resend_invoice_flagged_as_duplicate(ground_truth, categorized_transactions):
    pair = [t for t in categorized_transactions
            if t.get("invoice_number") == "INV-1041"]
    assert len(pair) == 2, (
        "INV-1041 must appear exactly twice (original + re-send), found %d" % len(pair))
    by_file = {t.get("source_file"): t for t in pair}
    assert set(by_file) == {ORIGINAL_INVOICE_FILE, RESEND_INVOICE_FILE}, (
        "unexpected sources for INV-1041: %r" % sorted(by_file))

    original = by_file[ORIGINAL_INVOICE_FILE]
    resend = by_file[RESEND_INVOICE_FILE]

    assert resend.get("is_duplicate") is True, (
        "re-send invoice must be flagged is_duplicate=True, got %r"
        % (resend.get("is_duplicate"),))
    assert resend.get("duplicate_of") == original.get("txn_id"), (
        "duplicate_of %r must point at the original txn_id %r"
        % (resend.get("duplicate_of"), original.get("txn_id")))
    assert not original.get("is_duplicate"), (
        "the original invoice must NOT be flagged as a duplicate")

    # Tie the behavior back to ground truth: same canonical vendor + number.
    expected = ground_truth["expected_duplicates"][0]
    assert expected["invoice_number"] == "INV-1041"


